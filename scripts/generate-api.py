def parse_params(text):
    """`(a: X, b?: Y, ...rest: Z[])` -> [(name, type_text, optional, rest)]."""
    text = text.strip()
    if text.startswith("("):
        text = text[1:]
    if text.endswith(")"):
        text = text[:-1]
    if not text.strip():
        return []
    out = []
    for part in split_top(text, ","):
        part = part.strip()
        rest = part.startswith("...")
        if rest:
            part = part[4:].strip()
        q = top_index(part, ":")
        if q < 0:
            raise Unsupported(f"parameter without a type: {part}")
        name = part[:q].strip()
        optional = name.endswith("?")
        if optional:
            name = name[:-1]
        if name.startswith("this"):  # `this: X` is a TS-only parameter
            continue
        out.append((name, part[q + 1 :].strip(), optional, rest))
    return out


def split_name_type(text):
    """`name: Type` / `method(a: X): Y` -> (name part, type text) using the top-level colon."""
    q = top_index(text, ":")
    if q < 0:
        raise Unsupported(f"declaration without a type: {text[:80]}")
    return text[:q].strip(), text[q + 1 :].strip()


def parse_members(body, separators=";"):
    """Split an interface / class / enum body into declarations with their doc comments."""
    members = []
    buf, doc, depth, i = "", [], 0, 0
    while i < len(body):
        if depth == 0 and body.startswith("/**", i):
            end = body.index("*/", i) + 2
            doc.append(body[i:end])
            i = end
            continue
        if depth == 0 and body.startswith("//", i):
            nl = body.find("\n", i)
            i = len(body) if nl < 0 else nl
            continue
        ch = body[i]
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "<":
            depth += 1
        elif ch == ">":
            if not (i > 0 and body[i - 1] == "="):
                depth -= 1
        if ch in separators and depth == 0:
            if buf.strip():
                members.append((buf.strip(), clean_doc(doc)))
            buf, doc = "", []
            i += 1
            continue
        buf += ch
        i += 1
    if buf.strip():
        members.append((buf.strip(), clean_doc(doc)))
    return members


def clean_doc(doc_lines):
    if not doc_lines:
        return ""
    text = "\n".join(doc_lines)
    text = text.replace("/**", "").strip()
    if text.endswith("*/"):
        text = text[:-2]
    lines = []
    for line in text.split("\n"):
        line = line.strip()
        if line.startswith("*"):
            line = line[1:].lstrip()
        # KDoc comments nest, so a literal `/*` or `*/` inside the text would break the comment.
        line = line.replace("/*", "&#47;*").replace("*/", "*&#47;")
        lines.append(line)
    return "\n".join(lines).strip()


def read_declarations(body, ns):
    """Split a namespace body into Decl objects (char scanner, so inline type literals survive)."""
    decls = []
    doc = []
    i, n = 0, len(body)
    braced = ("interface", "class", "enum", "namespace", "module")
    while i < n:
        ch = body[i]
        if ch.isspace():
            i += 1
            continue
        if body.startswith("/*", i):
            end = body.index("*/", i) + 2
            if body.startswith("/**", i):
                doc.append(body[i:end])
            i = end
            continue
        if ch == ";":
            i += 1
            continue
        if (
            body.startswith("export {", i)
            or body.startswith("export type {", i)
            or body.startswith("declare global", i)
        ):
            # A re-export list or a `declare global` block: skip the whole statement.
            end = body.index("{", i)
            depth = 1
            j = end + 1
            while depth:
                if body[j] == "{":
                    depth += 1
                elif body[j] == "}":
                    depth -= 1
                j += 1
            i = j
            continue
        if body.startswith("//", i):
            nl = body.find("\n", i)
            i = n if nl < 0 else nl
            continue
        m = re.match(
            r"(?:export\s+)?(?:declare\s+)?(?:abstract\s+)?"
            r"(class|interface|enum|type|function|const|let|var|namespace|module)\s+([\w$]+)",
            body[i:],
        )
        if not m:
            raise Unsupported(f"unexpected text in {ns}: {body[i:i + 120]!r}")
        decl = Decl(m.group(1), m.group(2), clean_doc(doc))
        doc = []
        header_end = i + m.end()
        if header_end < n and body[header_end] == "<":
            generics, length = read_generics(body, header_end)
            decl.generics = generics
            header_end += length
        start = i
        j = header_end
        depth = 0
        if decl.kind in braced:
            while j < n:
                c = body[j]
                if c in "([{":
                    depth += 1
                elif c in ")]}":
                    depth -= 1
                    if depth == 0 and c == "}":
                        j += 1
                        break
                j += 1
        else:
            while j < n:
                c = body[j]
                if c in "([{":
                    depth += 1
                elif c in ")]}":
                    depth -= 1
                elif c == ";" and depth == 0:
                    j += 1
                    break
                j += 1
        decl.body = body[start:j].strip()
        decl.inner = None
        if decl.kind in braced:
            decl.inner = decl.body[decl.body.index("{") + 1 : decl.body.rindex("}")]
        decls.append(decl)
        i = j
    if not decls:
        raise Unsupported(f"no declarations parsed in {ns}")
    return decls


def read_generics(text, start):
    """Read a `<...>` type parameter list starting at `start`; returns (text, length)."""
    depth, i = 0, start
    while i < len(text):
        ch = text[i]
        if ch == "<":
            depth += 1
        elif ch == ">":
            if i > 0 and text[i - 1] == "=":
                pass
            else:
                depth -= 1
                if depth == 0:
                    return text[start : i + 1], i + 1 - start
        i += 1
    raise Unsupported(f"unterminated type parameter list: {text[start:start + 80]}")


def parse_extends(members_text, include_implements=False):
    """`extends A, B<C>` from the text before the body's opening brace.

    The header of a declaration still carries its own keywords (`export interface ICodeEditor
    extends IEditor`), so `extends` is looked up instead of expected at offset 0. Classes also carry
    `implements`, and those interfaces make the class structurally assignable in Kotlin too.
    """
    head = members_text.strip().rstrip("{").strip()
    out = []
    for keyword in ("extends", "implements") if include_implements else ("extends",):
        at = _top_level_keyword(head, keyword)
        if at < 0:
            continue
        rest = head[at:].strip()
        # `implements` is the last clause; `extends` stops where `implements` starts.
        cut = _top_level_keyword(rest, "implements") if keyword == "extends" else -1
        if cut >= 0:
            rest = rest[:cut]
        out.extend(x.strip() for x in split_top(rest, ",") if x.strip())
    return out


def _top_level_keyword(head, keyword):
    """Offset just past `keyword` at bracket depth 0, or -1."""
    depth, i, n = 0, 0, len(head)
    while i < n:
        ch = head[i]
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth = max(0, depth - 1)
        elif (
            depth == 0
            and head.startswith(keyword, i)
            and (i == 0 or head[i - 1].isspace())
            and i + len(keyword) < n
            and head[i + len(keyword)].isspace()
        ):
            return i + len(keyword)
        i += 1
    return -1


