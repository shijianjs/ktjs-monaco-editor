class Generator:
    def __init__(self, version):
        self.version = version
        self.files = {}          # rel path -> list of lines
        self.unions = {}         # (package, name) -> list of branch kotlin types
        self.literals = {}       # (package, name) -> list of literal values
        self.declared = {}       # (package, name) -> kotlin type name
        self.decls = {}          # (package, name) -> the parsed declaration
        self.decl_kind = {}      # (package, name) -> interface / class / enum / type
        self.root_statics = []   # (class name, statics interface name, Kotlin accessor name)
        self.entries = []        # (namespace, name, kind, status) for coverage.md
        self.own_members = {}    # (package, name) -> set of Kotlin member names it declares
        self.shadowed = {}       # (package, name) -> member names a subtype re-declares (base drops them)
        self.supertypes = {}     # (package, name) -> raw `extends` list
        self.inherited_names = set()
        self.skipped = []
        self.emitted = {}
        self.intersections = {}
        self.seen_signatures = {}
        self.emitted_literals = set()
        self.alias_targets = {}
        self.generic_defaults = {}
        self.class_owners = set()
        self.override_names = set()
        self.shadowed_names = set()
        self.type_params = set()
        self.stats = {"interface": 0, "class": 0, "enum": 0, "type": 0, "function": 0, "const": 0}

    def type_param_names(self, generics):
        if not generics:
            return set()
        inner = generics.strip()[1:-1]
        return {
            re.match(r"([\w$]+)", part.strip()).group(1)
            for part in split_top(inner, ",")
            if part.strip()
        }

    def register_shape(self, pkg, decl):
        """Record a type's own member names and its `extends` list, for `override` and flattening."""
        if decl.kind not in ("interface", "class"):
            return
        self.decls[(pkg, decl.name)] = decl
        self.decl_kind[(pkg, decl.name)] = decl.kind
        head, _ = split_class_header(decl.body)
        self.supertypes[(pkg, decl.name)] = parse_extends(head, include_implements=decl.kind == "class")
        names = set()
        for raw, _doc in parse_members(decl.inner):
            text = raw.strip()
            if text.startswith("readonly "):
                text = text[len("readonly ") :]
            if text.startswith("["):
                continue
            p = top_index(text, "(")
            name_part = text[:p] if p >= 0 else split_name_type(text)[0]
            name_part = name_part.strip().rstrip("?").strip()
            for keyword in ("get ", "set ", "static "):
                if name_part.startswith(keyword):
                    name_part = name_part[len(keyword) :].strip()
            if re.match(r"^[\w$]+$", name_part):
                names.add(identifier(name_part))
        self.own_members[(pkg, decl.name)] = names

    def register_generic_defaults(self, pkg, decl):
        """Remember every type parameter's default (or bound) so bare references can be expanded."""
        if not decl.generics or decl.kind not in ("interface", "class", "type"):
            return
        inner = decl.generics.strip()
        inner = inner[1:-1] if inner.startswith("<") else inner
        specs = []
        for item in split_top(inner, ","):
            item = item.strip()
            m = re.match(r"^([\w$]+)(?:\s+extends\s+(.*?))?(?:\s*=\s*(.*))?$", item, re.S)
            if not m:
                continue
            specs.append((m.group(3).strip() if m.group(3) else None, m.group(2).strip() if m.group(2) else None))
        if specs:
            self.generic_defaults[(pkg, decl.name)] = specs

    def kotlin_generics(self, generics, pkg, owner, with_bounds=True):
        """`<T, U extends X>` -> `<T : JsAny?, U : X>` (or `<T, U>` when bounds are not allowed)."""
        if not generics:
            return ""
        inner = generics.strip()
        inner = inner[1:-1] if inner.startswith("<") else inner
        parts = []
        for item in split_top(inner, ","):
            item = item.strip()
            if not item:
                continue
            # `H = {}` alone (a default with no constraint) is just `H`.
            if re.match(r"^[\w$]+\s*=", item) and "extends" not in item:
                item = re.sub(r"\s*=.*$", "", item, flags=re.S).strip()
            m = re.match(r"^([\w$]+)(?:\s+extends\s+(.*))?$", item, re.S)
            if not m:
                raise Unsupported(f"type parameter `{item}` in {owner}")
            name, constraint = m.group(1), m.group(2)
            if constraint:
                # `T extends X = X` - the default type argument has no Kotlin counterpart.
                constraint = re.sub(r"\s+=\s+.*$", "", constraint, flags=re.S).strip()
            if not with_bounds:
                parts.append(name)
                continue
            bound = self.map_type(constraint, pkg, owner) if constraint else "JsAny?"
            parts.append(f"{name} : {bound}")
        return "<" + ", ".join(parts) + ">" if parts else ""

    # -- type mapping -------------------------------------------------------

    def map_type(self, text, pkg, owner, nullable=False, prop=None):
        text = text.strip()
        while text.startswith("(") and text.endswith(")") and top_index(text[1:-1], ")") < 0:
            text = text[1:-1].strip()
        if text.endswith(";"):
            text = text[:-1].strip()
        if text.startswith("readonly "):
            text = text[len("readonly ") :].strip()
        if text in PRIMITIVES:
            return PRIMITIVES[text]
        if text in FOREIGN:
            self.use_import(pkg, FOREIGN[text][1])
            return FOREIGN[text][0].rsplit(".", 1)[1]
        if text.endswith("[]"):
            inner = text[:-2].strip()
            if top_index(inner, "|") >= 0:
                inner = self.map_union(inner, pkg, owner, prop)
            else:
                inner = self.map_type(inner, pkg, owner)
            return f"Array<{inner}>"

        # function type: `(a: X) => Y` or `new (a: X) => Y`
        if text.startswith("new ") and top_index(text, "=>") >= 0:
            arrow = top_index(text, "=>")
            params = text[len("new ") : arrow].strip()
            return self.map_function(params, text[arrow + 2 :], pkg, owner, prop)
        if text.startswith("(") and top_index(text, "=>") >= 0:
            arrow = top_index(text, "=>")
            if text[:arrow].count("(") == text[:arrow].count(")"):
                return self.map_function(text[:arrow], text[arrow + 2 :], pkg, owner, prop)

        # generic application
        m = re.match(r"^([\w.$]+)<(.*)>$", text, re.S)
        if m and split_top(text[len(m.group(1)) + 1 :], "") == [text[len(m.group(1)) + 1 :]]:
            name, args = m.group(1), m.group(2)
            if name in ("Array", "ReadonlyArray"):
                return f"Array<{self.map_type(args, pkg, owner)}>"
            if name in ("Promise", "PromiseLike", "Thenable"):
                return f"Promise<{self.map_type(args, pkg, owner)}>"
            if name in ("Set", "ReadonlySet"):
                return f"JsSet<{self.map_type(args, pkg, owner)}>"
            if name in ("Map", "ReadonlyMap"):
                parts = split_top(args, ",")
                if len(parts) != 2:
                    raise Unsupported(f"Map with {len(parts)} args in {owner}")
                return f"JsMap<{self.map_type(parts[0], pkg, owner)}, {self.map_type(parts[1], pkg, owner)}>"
            if name == "Record":
                parts = split_top(args, ",")
                if len(parts) != 2:
                    raise Unsupported(f"Record with {len(parts)} args in {owner}")
                return f"Record<{self.map_type(parts[0], pkg, owner)}, {self.map_type(parts[1], pkg, owner)}>"
            if name in ("Partial", "Required", "Readonly", "Omit", "Pick", "Exclude", "Extract", "NonNullable", "ReturnType"):
                raise Unsupported(f"utility type {name}<...> in {owner}")
            args_k = ", ".join(self.map_type(a, pkg, owner) for a in split_top(args, ","))
            base = self.map_ref(name, pkg, owner, with_args=False)
            if base in ("JsAny", "JsAny?", "dynamic", "Boolean", "String", "Unit"):
                # An excluded or primitive base has no type parameters to apply.
                return base
            return f"{base}<{args_k}>"

        if top_index(text, "|") >= 0:
            return self.map_union(text, pkg, owner, prop)
        if top_index(text, "&") >= 0:
            return self.map_intersection(text, pkg, owner)
        if text.startswith("{"):
            return self.hoist_object(text, pkg, owner, prop)
        if text.startswith("["):
            # Tuple: Kotlin/JS has no tuple type, so a homogeneous tuple becomes an Array of its
            # element type and a mixed one has to stay `JsAny`.
            items = [i.strip() for i in split_top(text[1:-1], ",")]
            types = []
            for item in items:
                q = top_index(item, ":")
                types.append(item[q + 1 :].strip() if q >= 0 else item)
            mapped = [self.map_type(t, pkg, owner) for t in types]
            if len(set(mapped)) == 1:
                return f"Array<{mapped[0]}>"
            return "JsAny"
        if re.match(r"^['\"]", text):
            return "String"
        if re.match(r"^[-\d.]+$", text):
            return "Double"
        if text.startswith("typeof "):
            raise Unsupported(f"`typeof` type in {owner}")
        if " extends " in text and "?" in text:
            raise Unsupported(f"conditional type `{text}` in {owner}")
        if text == "this":
            return "JsAny"
        # A TypeScript type predicate (`thing is Uri`) narrows in TS only; on the Kotlin side the
        # callable still returns a Boolean.
        if re.match(r"^[\w$]+\s+is\s+[\w$.]+$", text):
            return "Boolean"
        # Indexed access (`T['items'][number]`) has no Kotlin counterpart over a type parameter.
        if re.search(r"\[\s*(number|['\"][^'\"]+['\"])\s*\]$", text):
            self.skipped.append(f"{owner}: indexed access `{text}` mapped to JsAny")
            return "JsAny"
        # An enum member used as a literal type (`MouseTargetType.UNKNOWN`) narrows to the enum.
        m = re.match(r"^([\w$]+)\.([\w$]+)$", text)
        if m and (m.group(1) in HAND_WRITTEN or any((p, m.group(1)) in self.declared for p in ("editor", "languages", "worker"))):
            return self.map_ref(m.group(1), pkg, owner)
        return self.map_ref(text, pkg, owner)

    def map_intersection(self, text, pkg, owner):
        """`A & B` becomes `external interface AAndB : A, B` - the same structural constraint."""
        branches = [b.strip() for b in split_top(text, "&")]
        mapped = [self.map_type(b, pkg, owner) for b in branches]
        name = "And".join(sanitize_branch(x) for x in mapped)
        key = (pkg, name)
        if key not in self.intersections:
            self.intersections[key] = {"supertypes": mapped, "owner": owner}
        return name

    def map_ref(self, name, pkg, owner, with_args=True):
        if name in self.type_params:
            return name
        if any((p, name) in EXCLUDED for p in ("root", "editor", "languages", "worker")):
            # Members typed with an excluded declaration degrade to JsAny; the exclusion and its
            # reason live in EXCLUDED / docs/development/coverage.md.
            self.skipped.append(f"{owner}: `{name}` is excluded, mapped to JsAny")
            return "JsAny"
        if "." in name:
            # A cross-namespace reference such as `editor.IMarkerData`.
            prefix, rest = name.split(".", 1)
            if prefix in ("editor", "languages", "worker") and (prefix, rest) in self.declared:
                if prefix != pkg:
                    self.use_import(pkg, prefix)
                return self.declared[(prefix, rest)]
        if name in HAND_WRITTEN:
            self.use_import(pkg, "root")
            return name
        if name in PRIMITIVES:
            return PRIMITIVES[name]
        if name in FOREIGN:
            self.use_import(pkg, FOREIGN[name][1])
            return FOREIGN[name][0].rsplit(".", 1)[1]
        for other_pkg in ("root", "editor", "languages", "worker"):
            if (other_pkg, name) in self.declared:
                other = self.declared[(other_pkg, name)]
                # A bare reference to a generic declaration (`HoverProvider`) has to spell out the
                # type arguments: Kotlin has no default type arguments, TS does.
                defaults = self.generic_defaults.get((other_pkg, name))
                if defaults and with_args:
                    args = ", ".join(
                        self.map_type(d or b, other_pkg, name) if (d or b) else "JsAny?"
                        for d, b in defaults
                    )
                    other = f"{other}<{args}>"
                if other_pkg == pkg:
                    return other
                self.use_import(pkg, other_pkg)
                return other
        if any((p, name) in EXCLUDED for p in ("root", "editor", "languages", "worker")):
            # Members typed with an excluded declaration degrade to JsAny; the exclusion and its
            # reason live in EXCLUDED / docs/development/coverage.md.
            self.skipped.append(f"{owner}: `{name}` is excluded, mapped to JsAny")
            return "JsAny"
        raise Unsupported(f"unknown type `{name}` referenced from {owner}")

    def map_function(self, params_text, ret_text, pkg, owner, prop=None):
        params = parse_params(params_text)
        if len(params) == 1 and not params[0][1]:
            args = ""
        else:
            args = ", ".join(
                self.map_type(t, pkg, owner, prop=(name[:1].upper() + name[1:] + "Arg") if name else None)
                for name, t, _, _ in params
            )
        ret = self.map_type(ret_text, pkg, owner)
        return f"({args}) -> {ret}"

    def shorten_union_name(self, mapped, text):
        """The Kotlin name of a union: its branches joined with `Or`, capped so it stays a usable file name.

        A union of eleven branches — `IMouseTargetUnknown | IMouseTargetTextarea | …` — joined naively
        produces a 218-character identifier. Dokka turns it into a directory per package and a file per
        declaration, and Windows refuses the path (`The filename, directory name, or volume label syntax
        is incorrect`), which silently drops that type from the published API docs. On any OS the name is
        also unusable in code.

        So: keep whole branch names while they fit, then say how many branches are left and add a hash of
        the upstream text to keep the name unique and stable across runs.
        """
        branches = [sanitize_branch(m) for m in mapped]
        joined = "Or".join(branches)
        if len(joined) <= MAX_UNION_NAME:
            return joined
        kept = []
        for branch in branches:
            if len("Or".join(kept + [branch])) > MAX_UNION_NAME - 20:
                break
            kept.append(branch)
        digest = hashlib.sha1(text.encode("utf-8")).hexdigest()[:8].upper()
        return "Or".join(kept) + f"Or{digest}Union"


    def map_union(self, text, pkg, owner, prop=None):
        branches = split_top(text, "|")
        kept, nullable = [], False
        for branch in branches:
            b = branch.strip()
            if b in ("undefined", "null"):
                nullable = True
                continue
            kept.append(b)
        if not kept:
            # `undefined | null`: the value carries no information Kotlin can check.
            return "JsAny?"
        if len(kept) == 1:
            mapped = self.map_type(kept[0], pkg, owner, prop=prop)
            return f"{mapped}?" if nullable else mapped
        if any(re.match(r"^['\"]", b) for b in kept) and all(re.match(r"^['\"]", b) for b in kept):
            name = prop or "LiteralUnion"
            return self.register_literal_union(pkg, name, [b.strip("'\"") for b in kept], owner)

        mapped = [self.map_type(b, pkg, owner, prop=prop) for b in kept]
        # Upstream repeats branches (`A | A`, or two branches that both map to `JsAny`); a union
        # cannot say anything new about them and duplicate factories would collide.
        mapped = list(dict.fromkeys(mapped))
        if any(m == "JsAny" for m in mapped):
            return "JsAny?" if nullable else "JsAny"
        if len(mapped) == 1:
            return f"{mapped[0]}?" if nullable else mapped[0]
        # A union of literals and other branches: keep the literal branch as String.
        name = self.shorten_union_name(mapped, text)
        if any(m in self.type_params for m in mapped):
            # A union over a type parameter cannot be hoisted to a top-level type.
            self.skipped.append(f"{owner}: union `{text}` over a type parameter mapped to JsAny")
            return "JsAny?"
        if (pkg, name) not in self.unions:
            self.unions[(pkg, name)] = {"branches": mapped, "owner": owner}
        self.use_import(pkg, "union")
        return f"{name}?" if nullable else name

    def hoist_object(self, text, pkg, owner, prop):
        """An inline object literal type becomes a named interface."""
        if prop is None:
            prop = "Result"
        base = pascal_owner(owner)
        cap = prop[:1].upper() + prop[1:]
        last = owner.split(".")[-1]
        if last.lower() == prop.lower() or cap == "Options":
            name = base[:1].upper() + base[1:] + "Options"
        else:
            name = base[:1].upper() + base[1:] + cap + "Options"
        self.emit_interface_from_body(pkg, name, text[1:-1], f"Upstream inline object type of `{prop}` in `{owner}`.")
        return name

    def register_literal_union(self, pkg, name, literals, owner):
        key = (pkg, name)
        # A name is reused by several owners (e.g. an inline literal union in a property); make the
        # stored value include every literal so all call sites agree.
        existing = self.literals.setdefault(key, set())
        existing.update(literals)
        return name

    # -- imports ------------------------------------------------------------

    def use_import(self, pkg, what):
        self.imports.setdefault(pkg, set()).add(what)

    # -- emitters -----------------------------------------------------------

    def add_line(self, pkg, rel, lines):
        self.files.setdefault((pkg, rel), []).extend(lines)

    def kdoc(self, doc, indent="", params=None):
        """The `/** ... */` block for an upstream doc comment.

        `params` is the member's Kotlin parameter names. Upstream doc comments occasionally name a
        parameter that the signature no longer has (`@param command` on a method taking `commands`),
        and Dokka then reports `Couldn't resolve link: [command]` for every build. A tag that names no
        parameter becomes a bullet instead: same text, no broken link.
        """
        if not doc:
            return []
        out = [indent + "/**"]
        for line in doc.split("\n"):
            stripped = line.strip()
            m = JSDOC_PARAM.match(stripped)
            if m and params is not None and m.group(1) not in params:
                out.append(f"{indent} * - `{m.group(1)}` — {m.group(2)}".rstrip())
                continue
            out.append(indent + " * " + line if line else indent + " *")
        out.append(indent + " */")
        return out

    def emit_interface_from_body(self, pkg, name, body, doc, extends=None, generics=None):
        if self.emitted.get((pkg, name)):
            return
        self.emitted[(pkg, name)] = True
        members = parse_members(body)
        lines = self.kdoc(doc)
        head = f"external interface {name}"
        if generics:
            head += generics
        if extends:
            head += " : " + ", ".join(extends)
        lines.append(head + " {")
        prev = self.type_params
        prev_shadowed = self.shadowed_names
        self.type_params = prev | self.type_param_names(generics)
        self.shadowed_names = self.shadowed.get((pkg, name), set())
        try:
            for raw, mdoc in members:
                lines.extend(self.emit_member(pkg, name, raw, mdoc))
        finally:
            self.type_params = prev
            self.shadowed_names = prev_shadowed
        lines.append("}")
        lines.append("")
        self.add_line(pkg, "types", lines)
        self.stats["interface"] += 1

    def emit_signature(self, pkg, owner, signature):
        """True when this Kotlin signature is new for `owner`; TS overloads otherwise collapse."""
        seen = self.seen_signatures.setdefault((pkg, owner), set())
        # Overloads that differ only in the return type or in parameter optionality cannot coexist in
        # Kotlin, and TS resolution would pick the first one anyway, so key on name + parameters.
        normalized = re.sub(r"\s+", " ", signature).strip()
        normalized = re.sub(r"\s*=\s*definedExternally", "", normalized)
        normalized = re.sub(r"\)\s*:.*$", ")", normalized)
        if normalized in seen:
            self.skipped.append(f"{owner}: duplicate overload `{normalized}` collapsed")
            return False
        seen.add(normalized)
        return True

    def resolve_member_owner(self, pkg, name):
        """The package a supertype name lives in."""
        name = name.split("<")[0].strip()
        if "." in name:
            prefix, rest = name.split(".", 1)
            if (prefix, rest) in self.own_members:
                return prefix, rest
            name = rest
        if (pkg, name) in self.own_members:
            return pkg, name
        for candidate in ("root", "editor", "languages", "worker"):
            if (candidate, name) in self.own_members:
                return candidate, name
        return pkg, name

    def collect_inherited(self, pkg, name, seen=None):
        """Every member name the supertypes of `(pkg, name)` declare, transitively."""
        return self.collect_inherited_from(pkg, self.supertypes.get((pkg, name), []), seen)

    def collect_inherited_from(self, pkg, sup_names, seen=None):
        seen = seen or set()
        out = set()
        for sup in sup_names:
            target = self.resolve_member_owner(pkg, sup)
            if target in seen:
                continue
            seen.add(target)
            out |= self.own_members.get(target, set())
            out |= self.collect_inherited(target[0], target[1], seen)
        return out

    def emit_member(self, pkg, owner, raw, doc):
        raw = raw.strip()
        if raw.startswith("readonly "):
            readonly, body = True, raw[len("readonly ") :]
        else:
            readonly, body = False, raw
        if body.startswith("get ") and "(" in body:
            # A TS accessor in a class: `get token(): CancellationToken`.
            accessor = body[len("get ") :]
            q = top_index(accessor, ":")
            head = accessor[:q].strip().rstrip("()").strip()
            out = self.kdoc(doc, "    ")
            out.append(f"    val {identifier(head)}: {self.map_type(accessor[q + 1 :].strip(), pkg, owner, prop=head)}")
            return out
        if body.startswith("set ") and "(" in body:
            # The matching `get` already declares the property; Kotlin/JS setters are not modelled.
            self.skipped.append(f"{owner}: setter `{body[:60]}`")
            return []
        if body.startswith("["):
            # index signature `[key: string]: V` or mapped type - not expressible on an interface
            self.skipped.append(f"{owner}: index signature `{body[:60]}`")
            return []
        if body.startswith("(") or body.startswith("<"):
            # call signature
            raise Unsupported(f"call signature in {owner}: {body[:60]}")
        q = top_index(body, ":")
        if q < 0:
            raise Unsupported(f"member without a type in {owner}: {body[:80]}")
        head = body[:q].strip()
        ttext = body[q + 1 :].strip()
        optional = head.endswith("?")
        if optional:
            head = head[:-1].strip()
        if head.startswith("new "):
            raise Unsupported(f"construct signature in {owner}")
        p = top_index(head, "(")
        if p >= 0:
            sig_head = head[:p].strip()
            method_generics = ""
            if sig_head.endswith(">"):
                open_at = matching_open_angle(sig_head)
                method_generics = sig_head[open_at:]
                sig_head = sig_head[:open_at].strip()
                # `T extends X = X` - the default type argument has no Kotlin counterpart.
                method_generics = re.sub(r"\s*=\s*[^,>]+\s*(?=[,>])", "", method_generics)
                method_generics = self.kotlin_generics(method_generics, pkg, owner)
            name = sig_head.strip()
            optional_method = name.endswith("?")
            if optional_method:
                name = name[:-1]
            params = parse_params(head[p:])
            out = self.kdoc(doc, "    ", params=[raw_name for raw_name, _, _, _ in params])
            prev = self.type_params
            self.type_params = prev | self.type_param_names(method_generics)
            try:
                params_kotlin = self.emit_params(pkg, owner, params)
                ret_kotlin = self.map_type(ttext, pkg, owner)
            finally:
                self.type_params = prev
            # A subtype that re-declares an inherited member to narrow its type keeps the precise
            # declaration; the base one is dropped by `compute_shadowed`.
            if identifier(name) in self.shadowed_names:
                self.skipped.append(
                    f"{owner}: `{name}` dropped, a subtype re-declares it with a narrower type"
                )
                return []
            # A no-arg `toString` hides `Any.toString` and needs an explicit `override`.
            override = "override " if name == "toString" and not params else ""
            if optional_method and not method_generics and name != "toString":
                # `name?(a: A): R` is an *optional* member of the JS object, not a callable method:
                # a consumer that supplies it writes `obj.name = { a -> ... }`, and one that does not
                # leaves the slot out. A Kotlin method would force every literal to carry a body, so
                # an optional method becomes a nullable function property.
                types = []
                for pname, ptext, poptional, prest in params:
                    ptype = self.map_type(ptext, pkg, owner, prop=pname)
                    if prest:
                        ptype = f"Array<{ptype}>"
                    types.append(ptype if not poptional or ptype.endswith("?") else ptype + "?")
                function_type = f"(({', '.join(types)}) -> {ret_kotlin})"
                # A `@param` tag on a property would name a parameter the Kotlin declaration does not
                # have; the descriptions become bullets instead.
                out = self.kdoc(doc, "    ", params=[])
                out.append(f"    {override}var {identifier(name)}: {function_type}?")
                return out
            out.append(f"    {override}fun {method_generics}{identifier(name)}({params_kotlin}): {ret_kotlin}")
            if not self.emit_signature(pkg, owner, out[-1]):
                return []
            return out
        name = head
        js_name = None
        if re.match(r"^['\"]", name):
            js_name = name.strip().strip("'\"")
            name = camel(js_name)
        if not name or not re.match(r"^[\w$]+$", name):
            raise Unsupported(f"member `{body[:80]}` in {owner}")
        out = self.kdoc(doc, "    ")
        if identifier(name) in self.shadowed_names:
            self.skipped.append(
                f"{owner}: `{name}` dropped, a subtype re-declares it with a narrower type"
            )
            return []
        if js_name:
            escaped = js_name.replace("\\", "\\\\").replace('"', '\\"')
            out.append(f'    @JsName("{escaped}")')
        kw = "val" if readonly else "var"
        typ = self.map_type(ttext, pkg, owner, prop=name)
        if optional and not typ.endswith("?"):
            typ += "?"
        override = "override " if identifier(name) in self.override_names else ""
        out.append(f"    {override}{kw} {identifier(name)}: {typ}")
        return out

    def is_callable(self, decl):
        members = parse_members(decl.inner)
        return bool(members) and all(raw.strip().startswith(("(", "<")) for raw, _ in members)

    def emit_callable(self, pkg, decl):
        """An interface whose only member is a call signature becomes a Kotlin function type."""
        raw, _ = parse_members(decl.inner)[0]
        close = match_close(raw, "(", ")")
        params = raw[1:close]
        ret = raw[close + 1 :].lstrip(":").strip()
        rest = "..." in params
        generics = self.kotlin_generics(decl.generics, pkg, decl.name, with_bounds=False)
        prev = self.type_params
        self.type_params = prev | self.type_param_names(decl.generics)
        try:
            mapped = self.map_function(params, ret, pkg, decl.name)
        finally:
            self.type_params = prev
        note = "upstream declares it as a call signature" + ("; JS passes the arguments variadically" if rest else "")
        self.emit_typealias(pkg, decl.name, mapped, decl.doc, note=note, generics=generics)

    def compute_shadowed(self):
        """Members a subtype re-declares to *narrow* its type.

        Kotlin forbids overriding with a narrowed parameter (and only allows a covariant return), so
        the base declaration is dropped and the subtype's precise one is kept. Structural supertypes
        (`Position : IPosition`) are exempt: there the class and the interface legitimately declare
        the same members.
        """
        for (pkg, name), decl in self.decls.items():
            structural = set(STRUCTURAL_SUPERTYPES.get((pkg, name), []))
            for sup in self.supertypes.get((pkg, name), []):
                if sup in structural:
                    continue
                target = self.resolve_member_owner(pkg, sup)
                base_names = self.own_members.get(target)
                if not base_names:
                    continue
                redeclared = self.own_members.get((pkg, name), set()) & base_names
                if redeclared:
                    self.shadowed.setdefault(target, set()).update(redeclared)

    def is_readonly_interface(self, pkg, name):
        """True when every property the interface declares is `readonly` (so a class can implement it)."""
        decl = self.decls.get((pkg, name))
        if decl is None:
            return False
        for raw, _doc in parse_members(decl.inner):
            text = raw.strip()
            if text.startswith("readonly ") or "(" in text:
                continue
            if text.startswith("["):
                continue
            return False
        return True

    def class_supertypes(self, pkg, decl, head):
        """The Kotlin supertypes of a class, plus the members that have to be re-declared."""
        raw_ext = parse_extends(head, include_implements=decl.kind == "class")
        ext, flattened, kept_raw = [], [], []
        for sup in raw_ext:
            target = self.resolve_member_owner(pkg, sup)
            if self.decl_kind.get(target) == "class":
                # Kotlin/JS cannot extend an `external class` (external classes are final), so the
                # inherited members are re-declared here instead of nesting the type.
                flattened.extend(self.flatten_super_members(target[0], target[1]))
                self.skipped.append(
                    f"{decl.name}: `extends {sup}` flattened (an external class cannot be extended in Kotlin)"
                )
            elif self.decl_kind.get(target) == "interface":
                if self.is_readonly_interface(target[0], target[1]):
                    ext.append(self.map_ref(sup, pkg, decl.name))
                    kept_raw.append(sup)
                else:
                    # `Uri implements UriComponents` but declares the components `readonly` while the
                    # interface declares them mutable: Kotlin cannot reconcile the two.
                    self.skipped.append(
                        f"{decl.name}: `implements {sup}` dropped (the interface declares mutable members)"
                    )
            else:
                ext.append(self.map_ref(sup, pkg, decl.name))
                kept_raw.append(sup)
        for extra in STRUCTURAL_SUPERTYPES.get((pkg, decl.name), []):
            mapped = self.map_ref(extra, pkg, decl.name)
            if mapped not in ext:
                ext.append(mapped)
                kept_raw.append(extra)
        return ext, flattened, kept_raw

    def emit_class(self, pkg, decl):
        """A class, as an `external class` or — in the root package — as an interface plus statics.

        The root classes (`Uri`, `Position`, `KeyMod`, …) are exported by the npm module as *values*.
        Kotlin's `@JsModule` on a class imports the module's **default export**, which monaco does not
        have, so those classes are modelled as a type-only `external interface` plus a
        `<Name>Statics` interface bound to the module's named export in `RootModule.kt`.
        """
        members = parse_members(decl.inner)
        head, _ = split_class_header(decl.body)
        ext, flattened, kept_raw = self.class_supertypes(pkg, decl, head)
        ctor = None
        instance, statics = [], []
        for raw, doc in members:
            if raw.strip().startswith("constructor"):
                ctor = parse_params(raw[raw.index("(") :])
            elif raw.strip().startswith("static "):
                statics.append((raw.strip()[len("static ") :], doc))
            else:
                instance.append((raw, doc))
        generics = self.kotlin_generics(decl.generics, pkg, decl.name)
        prev = self.type_params
        prev_inherited = self.inherited_names
        prev_override = self.override_names
        prev_shadowed = self.shadowed_names
        self.type_params = prev | self.type_param_names(decl.generics)
        self.shadowed_names = set()
        # Only the structural supertypes (`Position : IPosition`) contribute `override` members; the
        # flattened classes are re-declared here, so nothing in this class actually overrides them.
        self.override_names = self.collect_inherited_from(
            pkg, STRUCTURAL_SUPERTYPES.get((pkg, decl.name), [])
        )
        self.class_owners.add(decl.name)
        is_root = pkg == "root"
        lines = self.kdoc(decl.doc)
        if is_root:
            head_line = f"external interface {decl.name}{generics}"
        else:
            head_line = f"external class {decl.name}{generics}"
            if ctor:
                head_line += f"({self.emit_params(pkg, decl.name, ctor)})"
        if ext:
            head_line += " : " + ", ".join(ext)
        lines.append(head_line + " {")
        try:
            for raw, doc in instance:
                lines.extend(self.emit_member(pkg, decl.name, raw, doc))
            for raw, doc in flattened:
                lines.extend(self.emit_member(pkg, decl.name, raw, doc))
            if statics and not is_root:
                lines.append("")
                lines.append("    companion object {")
                for raw, doc in statics:
                    lines.extend(self.emit_static_member(pkg, decl.name, raw, doc))
                lines.append("    }")
        finally:
            self.type_params = prev
            self.inherited_names = prev_inherited
            self.override_names = prev_override
            self.shadowed_names = prev_shadowed
        lines.append("}")
        lines.append("")
        if is_root and statics:
            lines.extend(self.emit_root_statics(decl, statics))
        self.class_owners.discard(decl.name)
        self.add_line(pkg, "classes", lines)
        self.stats["class"] += 1

    def emit_root_statics(self, decl, statics):
        """The `static` members of a root class, on a separate interface bound to the module export."""
        statics_name = f"{decl.name}Statics"
        accessor = decl.name[:1].lower() + decl.name[1:] + "Statics"
        self.root_statics.append((decl.name, statics_name, accessor))
        lines = self.kdoc(
            f"The `static` members of monaco-editor's `{decl.name}`, reached through [Monaco.{decl.name}]."
        )
        lines.append(f"external interface {statics_name} {{")
        prev = self.type_params
        prev_shadowed = self.shadowed_names
        self.shadowed_names = set()
        try:
            for raw, doc in statics:
                lines.extend(self.emit_member("root", decl.name, raw, doc))
        finally:
            self.type_params = prev
            self.shadowed_names = prev_shadowed
        lines.append("}")
        lines.append("")
        return lines


    def flatten_super_members(self, pkg, name, seen=None):
        """The members of an external class and its own flattened supertypes, for re-declaration."""
        seen = seen or set()
        if (pkg, name) in seen:
            return []
        seen.add((pkg, name))
        decl = self.decls.get((pkg, name))
        if decl is None:
            return []
        out = []
        head, _ = split_class_header(decl.body)
        for sup in parse_extends(head):
            target = self.resolve_member_owner(pkg, sup)
            if self.decl_kind.get(target) == "class":
                out.extend(self.flatten_super_members(target[0], target[1], seen))
        for raw, doc in parse_members(decl.inner):
            if raw.strip().startswith(("constructor", "static ")):
                continue
            out.append((raw, doc))
        return out

    def emit_static_member(self, pkg, owner, raw, doc):
        """A static member of an external class becomes a companion member (`= definedExternally`)."""
        readonly, body = False, raw
        if body.startswith("readonly "):
            readonly, body = True, body[len("readonly ") :]
        name_part, ttext = split_name_type(body)
        ttext = ttext.rstrip(";").strip()
        out = self.kdoc(doc, "        ")
        p = top_index(name_part, "(")
        if p >= 0:
            name = name_part[:p].strip()
            out.append(f"        fun {identifier(name)}({self.emit_params(pkg, owner, parse_params(name_part[p:]))}): {self.map_type(ttext, pkg, owner)} = definedExternally")
            if not self.emit_signature(pkg, owner, out[-1]):
                return []
            return out
        kw = "val" if readonly else "var"
        out.append(f"        {kw} {identifier(name_part)}: {self.map_type(ttext, pkg, owner, prop=name_part)}")
        return out

    def emit_params(self, pkg, owner, params):
        out = []
        for name, ttext, optional, rest in params:
            typ = self.map_type(ttext, pkg, owner, prop=name)
            if rest:
                typ = f"Array<{typ}>"
            if optional:
                typ = typ if typ.endswith("?") else typ + "?"
                out.append(f"{identifier(name)}: {typ} = definedExternally")
            else:
                out.append(f"{identifier(name)}: {typ}")
        return ", ".join(out)


    def emit_root_module(self):
        """`RootModule.kt`: the named module imports behind the root classes' statics."""
        if not self.root_statics:
            return
        lines = []
        for name, statics_name, accessor in self.root_statics:
            lines.extend(
                self.kdoc(f"monaco-editor's `{name}` export, which carries its `static` members.")
            )
            lines.extend(
                [
                    f'@JsName("{name}")',
                    f"external val {accessor}: {statics_name}",
                    "",
                ]
            )
        self.add_line("root", "module", lines)

    def emit_enum(self, pkg, decl):
        members = []
        for raw, doc in parse_members(decl.inner, separators=","):
            m = re.match(r"^([\w$]+)\s*=\s*(.*)$", raw, re.S)
            if not m:
                raise Unsupported(f"enum member `{raw}` in {decl.name}")
            members.append((m.group(1), m.group(2).strip(), doc))
        numeric = all(re.match(r"^[-\d.]+$", v) for _, v, _ in members)
        literals = all(re.match(r"^['\"].*['\"]$", v) for _, v, _ in members)
        if not (numeric or literals):
            raise Unsupported(f"mixed enum values in {decl.name}")
        factory_arg = "Double" if numeric else "String"
        pkg_name = pkg
        lines = self.kdoc(decl.doc)
        lines.append(f"sealed external interface {decl.name}")
        lines.append("")
        lines.extend(self.kdoc(f"The members of [${decl.name}], as upstream declares them.".replace("$", "")))
        lines.append(f"fun {decl.name}(value: {factory_arg}): {decl.name} = value.unsafeCast<{decl.name}>()")
        lines.append("")
        const_name = decl.name + ("Values" if decl.name.endswith("s") else "s")
        lines.append(f"object {const_name} {{")
        for name, value, doc in members:
            lines.extend(self.kdoc(doc, "    "))
            if numeric:
                lines.append(f"    inline val {identifier(name)}: {decl.name} get() = {decl.name}({float(value)})")
            else:
                lines.append(f'    inline val {identifier(name)}: {decl.name} get() = {decl.name}("{value.strip(chr(39)+chr(34))}")')
        lines.append("}")
        lines.append("")
        self.add_line(pkg, "enums", lines)
        self.declared[(pkg, decl.name)] = decl.name
        self.stats["enum"] += 1

    def emit_type_alias(self, pkg, decl):
        text = decl.body
        m = re.match(r"^(?:export\s+)?type\s+[\w$]+(<.*?>)?\s*=\s*(.*)$", text, re.S)
        if not m:
            raise Unsupported(f"type alias parse failed: {text[:80]}")
        value = m.group(2).strip().rstrip(";").strip()
        generics = self.kotlin_generics(decl.generics, pkg, decl.name, with_bounds=False)
        prev = self.type_params
        self.type_params = prev | self.type_param_names(decl.generics)
        try:
            if top_index(value, "|") >= 0:
                branches = split_top(value, "|")
                if all(re.match(r"^['\"]", b) for b in branches):
                    self.register_literal_union(pkg, decl.name, [b.strip("'\"") for b in branches], decl.name)
                    self.emit_literal_object(pkg, decl.name, decl.doc)
                    self.declared[(pkg, decl.name)] = decl.name
                    self.stats["type"] += 1
                    return
                mapped = self.map_union(value, pkg, decl.name)
            elif value.startswith("{") and not generics:
                self.emit_interface_from_body(pkg, decl.name, value[1:-1], decl.doc)
                self.stats["type"] += 1
                return
            else:
                mapped = self.map_type(value, pkg, decl.name)
        finally:
            self.type_params = prev
        if mapped == decl.name:
            # `type X = X` is already the interface itself; nothing to add.
            self.skipped.append(f"{decl.name}: alias equals the type name")
            return
        self.emit_typealias(pkg, decl.name, mapped, decl.doc, generics=generics)

    def emit_typealias(self, pkg, name, target, doc, note=None, generics=""):
        lines = self.kdoc(doc)
        if note:
            lines.append(f"/** {note} */")
        lines.append(f"typealias {name}{generics} = {target}")
        lines.append("")
        self.add_line(pkg, "types", lines)
        self.declared[(pkg, name)] = name
        self.alias_targets[(pkg, name)] = target
        self.stats["type"] += 1

    def emit_literal_object(self, pkg, name, doc):
        if (pkg, name) in self.emitted_literals:
            # The same literal union reached through several members is emitted once.
            return
        self.emitted_literals.add((pkg, name))
        literals = sorted(self.literals[(pkg, name)])
        lines = self.kdoc(doc)
        lines.append(f"sealed external interface {name}")
        lines.append("")
        lines.append(f"fun {name}(value: String): {name} = value.unsafeCast<{name}>()")
        lines.append("")
        const_name = name + ("Values" if name.endswith("s") else "s")
        lines.append(f"object {const_name} {{")
        for lit in literals:
            prop = camel(lit)
            lines.append(f'    inline val {identifier(prop)}: {name} get() = {name}("{lit}")')
        lines.append("}")
        lines.append("")
        self.add_line(pkg, "literals", lines)

    def flush_intersections(self):
        for (pkg, name), info in sorted(self.intersections.items()):
            if (pkg, name) in self.declared:
                continue
            lines = [
                "/**",
                f" * `{' & '.join(info['supertypes'])}`, as `{info['owner']}` declares it in monaco-editor.",
                " *",
                " * An intersection of structural types is a structural interface that extends every branch.",
                " */",
                f"external interface {name} : {', '.join(info['supertypes'])}",
                "",
            ]
            self.add_line(pkg, "unions", lines)
            self.declared[(pkg, name)] = name

    def canonical(self, pkg, name):
        """Follow type aliases to the Kotlin type they stand for, so duck-typed branches dedupe."""
        seen = set()
        while True:
            hit = None
            for candidate in ("root", pkg, "editor", "languages", "worker"):
                if (candidate, name) in self.alias_targets:
                    hit = self.alias_targets[(candidate, name)]
                    break
            if not hit or hit == name or name in seen:
                return name
            seen.add(name)
            name = hit.split("<", 1)[0]

    def flush_unions(self):
        for (pkg, name), info in sorted(self.unions.items()):
            if (pkg, name) in self.declared:
                continue
            branches = info["branches"]
            lines = [
                f"/**",
                f" * `{' | '.join(branches)}`, as `{info['owner']}` declares it in monaco-editor.",
                f" */",
                f"external interface {name}",
                "",
            ]
            seen = set()
            for branch in branches:
                key = self.canonical(pkg, branch)
                if key in seen:
                    continue
                seen.add(key)
                lines.append(
                    f"fun {name}(value: {branch}): {name} = value.unsafeCast<{name}>()"
                )
            lines.append("")
            self.add_line(pkg, "unions", lines)
            self.declared[(pkg, name)] = name

    # -- namespace entry points --------------------------------------------

    def emit_namespace(self, pkg, ns, decls):
        iface = ns[:1].upper() + ns[1:] + "Namespace"
        # A namespace that only declares types (`worker`) is a type-only construct: the module exports
        # nothing under that name, so an interface for it would be a member nobody can ever reach.
        runtime_decls = [
            d
            for d in decls
            if d.kind in ("function", "const", "let", "var")
            and d.name not in HAND_WRITTEN
            and (ns, d.name) not in EXCLUDED
        ]
        if not runtime_decls:
            self.skipped.append(
                f"{ns}: namespace declares types only, so the module exports no value for it"
            )
            self.stats["interface"] -= 1
            return
        lines = [
            "/**",
            f" * The `monaco.{ns}` namespace, as the module exports it.",
            f" */",
            f"external interface {iface} {{",
        ]
        for decl in decls:
            if decl.name in HAND_WRITTEN or (ns, decl.name) in EXCLUDED:
                continue
            if decl.kind == "function":
                sig = decl.body.rstrip(";").strip()
                m = re.match(r"^(?:export\s+)?function\s+([\w$]+)\s*(<[^>]*>)?\s*\(", sig, re.S)
                if not m:
                    raise Unsupported(f"function parse failed in {ns}: {sig[:80]}")
                head = sig[m.end() - 1 :]
                close = match_close(head, "(", ")")
                params = head[1:close]
                ret = head[close + 1 :].lstrip(":").strip()
                out = self.kdoc(decl.doc, "    ")
                generics = self.kotlin_generics(decl.generics, pkg, ns + '.' + decl.name)
                prev = self.type_params
                self.type_params = prev | self.type_param_names(decl.generics)
                try:
                    params_kotlin = self.emit_params(pkg, ns + '.' + decl.name, parse_params(params))
                    ret_kotlin = self.map_type(ret, pkg, ns + '.' + decl.name)
                finally:
                    self.type_params = prev
                out.append(
                    f"    fun {generics}{identifier(decl.name)}({params_kotlin}): {ret_kotlin}"
                )
                lines.extend(out)
                self.stats["function"] += 1
            elif decl.kind == "const":
                m = re.match(r"^(?:export\s+)?const\s+([\w$]+)\s*:\s*(.*)$", decl.body, re.S)
                if not m:
                    raise Unsupported(f"const parse failed in {ns}: {decl.body[:80]}")
                type_text = m.group(2).strip().rstrip(";")
                typ = self.map_type(type_text, pkg, ns + '.' + decl.name, prop=decl.name)
                lines.extend(self.kdoc(decl.doc, "    "))
                lines.append(f"    val {identifier(decl.name)}: {typ}")
                self.stats["const"] += 1
            else:
                continue  # interfaces / enums / type aliases are emitted by their own emitters
        lines.append("}")
        lines.append("")
        self.add_line(pkg, "namespace", lines)
        self.declared[(pkg, iface)] = iface

    # -- driver -------------------------------------------------------------

    def run(self):
        text = API.read_text(encoding="utf-8")
        # `<H = {}>` (an empty object as a type-parameter default) puts braces inside a declaration
        # header, which the brace scanner below would read as the body. Give the default a name;
        # `EmptyObject` maps to JsAny and is dropped anyway (Kotlin has no default type arguments).
        text = re.sub(r"=\s*\{\s*\}", "= EmptyObject", text)
        # `declare namespace languages` appears twice in the file (interfaces, then consts), so the
        # bodies of one namespace have to be concatenated instead of overwritten.
        bodies_by_ns = {}
        for ns, body in find_namespaces(text, "editor.api"):
            if ns in ("editor", "languages", "worker"):
                bodies_by_ns.setdefault(ns, []).append(body)
        decls_by_ns = {
            ns: [decl for body in bodies for decl in read_declarations(body, ns)]
            for ns, bodies in bodies_by_ns.items()
        }
        # The module's own top-level declarations (Position, Range, Uri, KeyCode, …) live outside the
        # namespaces and have to be registered before anything references them.
        root_body = blank_namespaces(text)
        root_decls = read_declarations(root_body, "root")

        # First pass: every name a namespace declares is a known type, so members may reference
        # interfaces that have not been emitted yet (emission order follows the declaration order).
        for ns, decls in decls_by_ns.items():
            self.declared[(ns, ns[:1].upper() + ns[1:] + "Namespace")] = ns[:1].upper() + ns[1:] + "Namespace"
            for decl in decls:
                if decl.kind in ("interface", "class", "enum", "type") and decl.name not in HAND_WRITTEN:
                    self.declared[(ns, decl.name)] = decl.name
                    self.register_generic_defaults(ns, decl)
                    self.register_shape(ns, decl)
        for decl in root_decls:
            if decl.kind in ("interface", "class", "enum", "type") and decl.name not in HAND_WRITTEN:
                self.declared[("root", decl.name)] = decl.name
                self.register_generic_defaults("root", decl)
                self.register_shape("root", decl)

        self.compute_shadowed()

        # Coverage bookkeeping: one entry per declaration, recorded before emission so a failure later
        # in the run still leaves the list complete.
        for ns, decls in decls_by_ns.items():
            self.entries.extend(self.coverage_entries(ns, decls))
        self.entries.extend(self.coverage_entries("root", root_decls))

        for ns, decls in decls_by_ns.items():
            self.emit_namespace(ns, ns, decls)
            for decl in decls:
                if decl.name in HAND_WRITTEN:
                    continue
                if (ns, decl.name) in EXCLUDED:
                    self.skipped.append(f"excluded {ns}.{decl.name}: {EXCLUDED[(ns, decl.name)]}")
                    continue
                if decl.kind == "enum":
                    self.emit_enum(ns, decl)
                elif decl.kind == "interface":
                    if self.is_callable(decl):
                        self.emit_callable(ns, decl)
                        continue
                    head, body_inner = split_class_header(decl.body)
                    ext = [self.map_ref(x, ns, decl.name) for x in parse_extends(head)]
                    self.emit_interface_from_body(
                        ns,
                        decl.name,
                        body_inner,
                        decl.doc,
                        extends=ext,
                        generics=self.kotlin_generics(decl.generics, ns, decl.name),
                    )
                elif decl.kind == "class":
                    self.emit_class(ns, decl)
                elif decl.kind == "type":
                    self.emit_type_alias(ns, decl)
                elif decl.kind in ("function", "const"):
                    pass  # emitted into the namespace interface
                else:
                    raise Unsupported(f"declaration kind {decl.kind} ({decl.name}) in {ns}")
            self.stats["interface"] -= 1  # the namespace interface itself
        for decl in root_decls:
            if decl.name in HAND_WRITTEN:
                continue
            if decl.kind == "enum":
                self.emit_enum("root", decl)
            elif decl.kind == "interface":
                if self.is_callable(decl):
                    self.emit_callable("root", decl)
                    continue
                head, body_inner = split_class_header(decl.body)
                ext = [self.map_ref(x, "root", decl.name) for x in parse_extends(head)]
                self.emit_interface_from_body(
                    "root",
                    decl.name,
                    body_inner,
                    decl.doc,
                    extends=ext,
                    generics=self.kotlin_generics(decl.generics, "root", decl.name),
                )
            elif decl.kind == "class":
                self.emit_class("root", decl)
            elif decl.kind == "type":
                self.emit_type_alias("root", decl)
            elif decl.kind in ("const", "function", "let", "var"):
                self.skipped.append(f"root-level {decl.kind} {decl.name} (not part of the public API)")
            else:
                raise Unsupported(f"declaration kind {decl.kind} ({decl.name}) at the module root")

        self.flush_intersections()
        self.flush_unions()
        self.emit_root_module()
        # Literal unions registered while emitting members but declared as their own type alias are
        # already written; the rest need an object now.
        for (pkg, name), literals in sorted(self.literals.items()):
            if (pkg, "literals", name) in self.files:
                continue
            self.emit_literal_object(pkg, name, f"`{' | '.join(sorted(literals))}`.")
        return self

    def coverage_entries(self, ns, decls):
        """(namespace, name, kind, status) for each declaration, for `coverage.md`.

        `done` is "the generator writes it"; `excluded` is "deliberately left out" and points at the
        reason in `EXCLUDED`; `pending` is anything with no counterpart in Kotlin that the run drops.
        """
        out = []
        for decl in decls:
            if (ns, decl.name) in EXCLUDED:
                out.append((ns, decl.name, decl.kind, "excluded"))
            elif decl.kind in ("interface", "class", "enum", "type", "function", "const"):
                out.append((ns, decl.name, decl.kind, "done"))
            else:
                out.append((ns, decl.name, decl.kind, "pending"))
        return out

