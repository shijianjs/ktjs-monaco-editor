# --------------------------------------------------------------------------- splitting helpers


def split_top(text, separators):
    """Split `text` on any of `separators` at bracket depth 0."""
    parts, cur, depth, i = [], "", 0, 0
    while i < len(text):
        ch = text[i]
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "<":
            depth += 1
        elif ch == ">":
            if i > 0 and text[i - 1] == "=":
                pass  # arrow `=>`
            else:
                depth -= 1
        if ch in separators and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
        i += 1
    parts.append(cur)
    return [p.strip() for p in parts if p.strip()]


def top_index(text, needle):
    """Index of `needle` at bracket depth 0, or -1."""
    depth, i = 0, 0
    while i < len(text):
        ch = text[i]
        if text.startswith(needle, i) and depth == 0:
            return i
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "<":
            depth += 1
        elif ch == ">" and not (i > 0 and text[i - 1] == "="):
            depth -= 1
        i += 1
    return -1


